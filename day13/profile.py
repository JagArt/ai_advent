"""Профиль пользователя: с кем говорит агент и в каком виде ждут ответ.

Слой над памятью, а не её четвёртый уровень. Память отвечает на вопрос «что мы
знаем и о чём договорились», профиль — «кому и как это сказать». Поэтому он
устроен иначе: у памяти только свободные формулировки, а у профиля половина
устройства — шкалы с фиксированными значениями.

    шкалы           стиль, длина, формат, уровень, обращение   значение из списка
    свободные       о себе, предпочтения, ограничения          любая формулировка

Шкала нужна там, где вариантов заведомо немного и важно, чтобы модель поняла их
одинаково: «коротко» — это всегда одна и та же строка в промпте, а не как модель
сегодня прочитает слово «кратко». Свободный пункт нужен там, где список заранее
не составить: «примеры кода на Python 3.12», «без эмодзи», «сначала вывод, потом
объяснение». Одно без другого не работает: на одних шкалах профиль не описать, а
на одних пунктах он расползается в пожелания, из которых модель выбирает сама.

Модуль ничего не знает ни про базу, ни про сеть: он хранит профиль и собирает из
него системное сообщение. Пункт профиля устроен так же, как пункт памяти, и берёт
её тип: раздел, формулировка и то, как он сюда попал.
"""

from dataclasses import dataclass, field

from openai.types.chat import (
    ChatCompletionMessageParam,
    ChatCompletionSystemMessageParam,
)

from memory import Item

# Четвёртый адрес для находки: не уровень памяти, а профиль. Стоит рядом с
# longterm и working в карточке, но пишется в свои таблицы.
PROFILE = "profile"

PROFILE_NAME = "профиль"

# Разделы фиксированы по той же причине, что и в памяти: иначе модель заводит
# новый раздел на каждый ход. «О себе» — кто собеседник, остальные два — как с ним
# говорить: чего он хочет и чего не хочет.
SECTIONS = ("о себе", "предпочтения", "ограничения")


@dataclass(frozen=True)
class Scale:
    """Шкала предпочтения: список значений, у каждого — готовая строка для промпта.

    Значение хранится словом («коротко»), а в модель уходит формулировкой. Так
    интерфейс остаётся списком из трёх слов, а промпт — внятной инструкцией.
    """

    key: str
    about: str
    values: dict[str, str]

    @property
    def options(self) -> tuple[str, ...]:
        return tuple(self.values)

    def phrase(self, value: str) -> str:
        return self.values.get(value, "")


# Формулировки — то, что на самом деле управляет ответом, поэтому они написаны как
# требования, а не как пожелания. Значения разных шкал не должны спорить между
# собой: «коротко» ограничивает объём, «списки» — вид, и вместе это короткий список.
SCALES = (
    Scale(
        key="стиль",
        about="тон ответа",
        values={
            "деловой": "Тон деловой: без светских оборотов, сразу к делу.",
            "дружелюбный": "Тон дружелюбный: живая разговорная речь, лёгкая шутка уместна.",
            "наставнический": "Тон наставника: объясняй спокойно и по шагам, подбадривай.",
        },
    ),
    Scale(
        key="длина",
        about="сколько текста в ответе",
        values={
            "коротко": "Длина: два-три предложения, только ответ на заданный вопрос.",
            # Про таблицу сказано отдельно, потому что шкалы не должны спорить: с
            # «один абзац» любая таблица оказывалась нарушением длины, хотя её
            # просит другая шкала.
            "средне": "Длина: до шести предложений связного текста, не считая таблицу, если она нужна.",
            "подробно": "Длина: разбирай подробно, несколько абзацев — это нормально.",
        },
    ),
    Scale(
        key="формат",
        about="как разложен ответ",
        values={
            "проза": "Формат: связный текст. Списков и таблиц не делай.",
            "списки": "Формат: короткие пункты списком, по строке на мысль.",
            "таблицы": "Формат: где есть что сравнить — таблица, остальное короткими пунктами.",
        },
    ),
    Scale(
        key="уровень",
        about="насколько объяснять термины",
        values={
            "новичок": "Уровень собеседника: новичок. Расшифровывай каждый термин при первом упоминании.",
            "средний": "Уровень собеседника: средний. Общие термины не поясняй, редкие — поясняй.",
            "эксперт": "Уровень собеседника: эксперт. Говори терминами, очевидное не объясняй.",
        },
    ),
    Scale(
        key="обращение",
        about="на ты или на вы",
        # Формулировка короткая после замера: вариант с перечислением запрещённых
        # форм («форм „вы“, „вам“, „ваш“ быть не должно») дал у судьи 10 из 18 против
        # 15 — названное в запрете модель охотнее повторяет, чем избегает.
        values={
            "ты": "Обращайся на «ты».",
            "вы": "Обращайся на «вы».",
        },
    ),
)

SCALE_KEYS = tuple(scale.key for scale in SCALES)
BY_KEY = {scale.key: scale for scale in SCALES}

# Блок уходит системным сообщением и стоит первым из блоков: он не про содержание
# разговора, а про форму всего, что дальше. Про «не спрашивая» сказано прямо —
# иначе модель начинает уточнять, точно ли нужен короткий ответ.
INTRO = (
    "Профиль пользователя — с кем ты говоришь и в каком виде он ждёт ответ.\n"
    "Это не справка, а требования к каждому твоему ответу: соблюдай их, "
    "не переспрашивая и не проговаривая вслух.\n"
)


@dataclass(frozen=True)
class Preset:
    """Профиль до начала общения: то же, что seed для долговременной памяти."""

    id: str
    name: str
    scales: dict[str, str]
    items: tuple[tuple[str, str], ...]


@dataclass(frozen=True)
class Profile:
    """Профиль целиком: имя, значения шкал и свободные пункты по разделам."""

    id: str
    name: str
    scales: dict[str, str] = field(default_factory=dict)
    items: tuple[Item, ...] = ()

    def value(self, key: str) -> str:
        """Значение шкалы или первое из списка: пустой шкалы в профиле не бывает."""
        scale = BY_KEY[key]
        value = self.scales.get(key, "")
        return value if value in scale.values else scale.options[0]

    @property
    def count(self) -> int:
        return len(self.items)

    @property
    def text(self) -> str:
        lines = [f"Собеседник: {self.name}.", "Как отвечать:"]
        lines.extend(f"- {BY_KEY[key].phrase(self.value(key))}" for key in SCALE_KEYS)

        for section in SECTIONS:
            chosen = [item for item in self.items if item.section == section]
            if not chosen:
                continue
            lines.append(f"{section}:")
            lines.extend(f"- {item.text}" for item in chosen)

        return "\n".join(lines)

    def as_param(self) -> ChatCompletionMessageParam:
        return ChatCompletionSystemMessageParam(role="system", content=INTRO + self.text)

    def as_dict(self) -> dict[str, object]:
        return {
            "id": self.id,
            "name": self.name,
            # Шкалы отдаются полным набором: страница рисует селектор на каждую, и
            # пропущенная в базе шкала не должна оставлять в блоке дырку.
            "scales": {key: self.value(key) for key in SCALE_KEYS},
            "items": [item.as_dict() for item in self.items],
        }


def build(row: dict[str, object]) -> Profile:
    """Профиль из того, что вернула база: имя, шкалы и пункты одной строкой."""
    scales = row.get("scales")
    items = row.get("items")
    return Profile(
        id=str(row["id"]),
        name=str(row["name"]),
        scales=dict(scales) if isinstance(scales, dict) else {},
        items=tuple(
            Item(
                id=int(item["id"]),
                section=str(item["section"]),
                text=str(item["text"]),
                origin=str(item["origin"]),
            )
            for item in (items if isinstance(items, list) else [])
            # Раздел вне списка означает рассинхрон кода и базы: такой пункт не
            # отрисуется в блоке, и в запрос его пускать тоже незачем.
            if item["section"] in SECTIONS
        ),
    )


def section_of(raw: object) -> str:
    """Раздел из ответа модели — к списку разделов профиля."""
    name = " ".join(str(raw).split()).lower()
    if name in SECTIONS:
        return name
    for section in SECTIONS:
        if name and (section.startswith(name) or name.startswith(section)):
            return section
    # Пожелание в профиле чаще запрет, чем просьба, и «ограничения» — единственный
    # раздел, где лишний пункт не выдаёт себя за факт о человеке.
    return "ограничения"


def scale_of(raw: object) -> Scale | None:
    """Шкала из ответа модели: неизвестное имя — не шкала, а выдумка."""
    name = " ".join(str(raw).split()).lower()
    return BY_KEY.get(name)
