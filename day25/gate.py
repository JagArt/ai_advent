"""Право не отвечать: порог в коде до вызова модели и правило в промпте после.

Задание дня требует, чтобы при слабом контексте ассистент сказал «не знаю» и
попросил уточнить. Слоя для этого два, и они не дублируют друг друга — так же,
как в [day14](../day14/invariants.py) детектор в коде и модель-аудитор стояли
рядом, а не вместо.

**Слой в коде** срабатывает до запроса и смотрит не на текст, а на числа: пуст
ли контекст и какова оценка лучшей дошедшей выдержки. Он дёшев, детерминирован
и не зависит от того, в каком настроении модель. Главное же — он единственный,
кто способен отказать *не заплатив*: на вопросе вне базы запрос с пятью
выдержками не уходит вовсе.

**Слой в промпте** — правило `unknown: true` из [cite.py](cite.py). Он нужен
там, где числа слепы: выдержка про тот же модуль получает от реранкера высокую
оценку и порог проходит, а ответа на вопрос в ней нет. Отличить это можно
только прочитав, и читает модель.

## Почему порог не равен порогу фильтра

Порог фильтра в [rerank.py](rerank.py) отвечает на вопрос «стоит ли нести эту
выдержку в контекст», порог отказа — на другой: «есть ли в контексте то, чем
вообще можно ответить». Это разные решения, и совпадать им незачем. Фильтр
пропускает оценку 2 («отвечает частично или содержит нужную деталь») — такая
выдержка полезна рядом с прямым ответом, но сама по себе ответом не является.
Значение выбрано разверткой на двух наборах: `python day24/scenarios.py gate`.

## Уточняющий вопрос собирается, а не сочиняется

Просить уточнение отдельным вызовом модели значило бы платить за отказ ровно
то, чего отказ и должен избежать. Поэтому вопрос собирается шаблоном из того,
что поиск всё-таки принёс: названия двух ближайших файлов — это подсказка,
по которой человек поймёт, в какую сторону база вообще смотрит. Если пул пуст,
подсказывать нечем, и шаблон остаётся общим.

## Отказ в чате знает, о чём шёл разговор

В day24 отказ был концом эпизода: вопрос не из базы — ответа нет. В диалоге
отказ стоит посередине, и после него разговор продолжается, поэтому уточнение
обязано держать ту же цель, что и остальные ходы. Шаблон получает память задачи
и называет цель вместе с файлами: «мы выбираем стратегию памяти, ближе всего
лежат такие-то файлы, уточните, о каком дне речь».

Это единственное место, где слой в коде вообще смотрит на состояние, и смотрит
он только для формулировки. Решение — отвечать или нет — по-прежнему принимается
по числам поиска: разрешать отказ или запрещать его в зависимости от того, что
записано в памяти задачи, значило бы отдать порогу право передумать.
"""

from dataclasses import dataclass

from cite import REFUSAL
from pipeline import Context
from state import TaskState

# Порог отказа в шкале реранкера 0..1, где 1.0 — «выдержка содержит прямой
# ответ», 2/3 — «отвечает частично». Значение снято разверткой на обоих наборах
# (`python day24/scenarios.py gate`), и выбирать было почти не из чего:
#
#   порог 0.00–0.50 — отказ срабатывает только на пустом контексте: 3 верных
#     отказа из 8, все на вопросах, где поиск не принёс вообще ничего;
#   порог 0.67–1.00 — 5 верных отказов из 8, и все четыре вопроса «вне базы»
#     закрыты;
#   ложных отказов нет ни при одном пороге: на всех восьми вопросах
#     контрольного набора, ответ на которые в базе есть, хотя бы одна выдержка
#     получила от реранкера 1.0.
#
# Берём верхнее значение: раз цена нулевая, строгость бесплатна. Но нулевая она
# на этой линейке, а не вообще — корпус, где прямого ответа нет ни в одном
# чанке, платил бы за порог 1.0 отказами на верных вопросах.
THRESHOLD = 1.0

# Сколько файлов называть в уточнении. Один выглядит как ответ, три — как
# список: два ровно настолько, чтобы стало видно направление.
HINTS = 2

EMPTY = "контекст пуст"
BELOW = "ниже порога"
MODEL = "правило в промпте"
PASSED = ""


@dataclass(frozen=True)
class Verdict:
    """Решение слоя в коде: пускать ли вопрос к модели и почему нет."""

    passed: bool
    reason: str
    best: float | None
    threshold: float
    clarify: str = ""

    @property
    def text(self) -> str:
        """Готовый отказ. Его можно отдать наружу, не обращаясь к модели."""
        return f"{REFUSAL}. {self.clarify}".strip()

    def as_dict(self) -> dict[str, object]:
        return {
            "passed": self.passed,
            "reason": self.reason,
            "best": self.best,
            "threshold": self.threshold,
            "clarify": self.clarify,
        }


def hints(context: Context) -> list[str]:
    """Ближайшие файлы: сначала дошедшие, потом отсеянные по месту в поиске."""
    ordered = [source.path for source in context.sources]
    ordered += [
        item.hit.path for item in sorted(context.dropped, key=lambda item: item.place)
    ]

    paths: list[str] = []
    for path in ordered:
        if path not in paths:
            paths.append(path)
        if len(paths) >= HINTS:
            break

    return paths


def goal_of(current: TaskState | None) -> str:
    """Напоминание о цели перед уточнением. Без состояния — пустая строка."""
    if current is None or current.goal is None:
        return ""
    return f"Мы разбираем: {current.goal.text}. "


def clarify(context: Context | None, current: TaskState | None = None) -> str:
    """Уточняющий вопрос из пула. Без модели и без сети."""
    goal = goal_of(current)
    found = hints(context) if context else []

    if not found:
        return (
            f"{goal}По этому вопросу в базе не нашлось ничего. "
            "Назовите день, файл или термин проекта — тогда будет что искать."
        )

    named = " и ".join(f"`{path}`" for path in found)
    return (
        f"{goal}Ближе всего в базе лежат {named}, но прямого ответа в них нет. "
        "Уточните, о каком дне или модуле речь."
    )


def inspect(
    context: Context | None,
    threshold: float = THRESHOLD,
    current: TaskState | None = None,
) -> Verdict:
    """Слой в коде на один контекст. Решение принимается до вызова модели."""
    if context is None or not context.sources:
        return Verdict(
            passed=False,
            reason=EMPTY,
            best=None,
            threshold=threshold,
            clarify=clarify(context, current),
        )

    best = context.best_relevance

    # Оценок нет вовсе — реранкер выключен или сорвался. Отказывать по
    # отсутствию числа нельзя: это отказ от незнания, а не от слабого контекста.
    if best is None:
        return Verdict(passed=True, reason=PASSED, best=None, threshold=threshold)

    if best < threshold:
        return Verdict(
            passed=False,
            reason=BELOW,
            best=best,
            threshold=threshold,
            clarify=clarify(context, current),
        )

    return Verdict(passed=True, reason=PASSED, best=best, threshold=threshold)
