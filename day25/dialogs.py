DIALOGUES = {dialogue.key: dialogue for dialogue in (MEMORY, MCP)}
KEYS = tuple(DIALOGUES)


def load(key: str) -> Dialogue:
    if key not in DIALOGUES:
        raise ValueError(f"Сценария {key!r} нет. Есть: {', '.join(KEYS)}.")
    return DIALOGUES[key]


def every() -> list[Dialogue]:
    return [DIALOGUES[key] for key in KEYS]
