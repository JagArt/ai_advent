"""Два длинных сценария: по чему меряется память диалога.

Задание просит проверить чат на двух разговорах по 10–15 сообщений и убедиться,
что ассистент не теряет цель и продолжает выдавать источники. Набор вопросов
day22–day24 для этого не годится принципиально: там каждая строка самодостаточна
и порядок строк не значит ничего, а здесь значение имеет ровно порядок.

Поэтому реплики размечены, и разметка — это и есть замер. У каждой реплики есть
род, и от рода зависит, что с хода спрашивают:

    goal         ставит цель разговора
    constraint   фиксирует ограничение, которое дальше обязаны соблюдать
    term         придаёт слову конкретный смысл
    followup     обычный следующий вопрос той же темы
    referential  ссылается на прошлый ход: без разрешения ссылок не искабельна
    digression   уводит в сторону — проверка, что цель от этого не теряется
    probe        верно отвечается только тем, кто помнит цель и ограничения

Род `probe` — главный. Остальные роды проверяются детекторами в коде: ссылка
разрешена, если ход сослался на ожидаемый файл; рамка соблюдена, если в ответе
есть нужное слово и нет запрещённого. А вот «ответ учитывает, что у человека
только SQLite» детектором не ловится, и такие ходы отданы судье.

## Почему пробы не спрашивают «какая у нас цель»

Напрашивалась прямая проверка: на десятом ходе спросить «напомни, что мы решаем».
Отвергнуто, и причина устройство, а не вкус. Форма ответа из
[cite.py](cite.py) требует к каждому утверждению дословную цитату из выдержек, а
цели разговора в базе проекта нет и быть не может — она родилась в этом диалоге.
Прямая проверка мерила бы не память, а способность модели нарушить схему.

Поэтому цель проверяется двумя другими способами, и оба честнее. Во-первых,
`probe` — вопрос, сформулированный так, что без цели на него нельзя ответить
правильно: «что из этого мне подойдёт» без «мне» смысла не имеет. Во-вторых,
саму цель видно в памяти задачи, и сверять её с исходной формулировкой можно
напрямую, без участия модели-ответчика.

## Почему второй сценарий не про RAG

План дня предполагал разговор про сборку RAG. От этого пришлось отказаться по
составу корпуса: day22, day23 и day24 из индекса исключены
(см. [corpus.py](corpus.py)), и спрашивать про RAG значило бы вести диалог по
теме, которой в базе нет, — получился бы сценарий из тринадцати отказов.
Вместо этого второй разговор про MCP-слой: day16–day20 в корпусе целиком, пять
папок с кодом и документацией, и ссылочные цепочки между ними естественные.
"""

from dataclasses import dataclass

GOAL = "goal"
CONSTRAINT = "constraint"
TERM = "term"
FOLLOWUP = "followup"
REFERENTIAL = "referential"
DIGRESSION = "digression"
PROBE = "probe"

KINDS = (GOAL, CONSTRAINT, TERM, FOLLOWUP, REFERENTIAL, DIGRESSION, PROBE)

KIND_TITLES = {
    GOAL: "цель",
    CONSTRAINT: "ограничение",
    TERM: "термин",
    FOLLOWUP: "продолжение",
    REFERENTIAL: "ссылка",
    DIGRESSION: "отвлечение",
    PROBE: "проба",
}


@dataclass(frozen=True)
class Say:
    """Реплика сценария вместе с тем, что с неё спрашивают.

    `expect_paths` — файлы, хотя бы один из которых ход обязан процитировать.
    Проверка по подстроке пути, а не по равенству: `day10/` годится, когда
    неважно, README это или код, а `day11/storage.py` — когда важно.
    """

    text: str
    kind: str
    expect_paths: tuple[str, ...] = ()
    must_say: tuple[str, ...] = ()
    must_not_say: tuple[str, ...] = ()
    about: str = ""

    @property
    def framed(self) -> bool:
        """Есть ли у хода рамка, которую можно проверить детектором."""
        return bool(self.must_say or self.must_not_say)

    def as_dict(self) -> dict[str, object]:
        return {
            "text": self.text,
            "kind": self.kind,
            "kind_title": KIND_TITLES[self.kind],
            "expect_paths": list(self.expect_paths),
            "must_say": list(self.must_say),
            "must_not_say": list(self.must_not_say),
            "about": self.about,
        }


@dataclass(frozen=True)
class Dialogue:
    """Сценарий: цель, по которой сверяют память, и размеченные реплики."""

    key: str
    title: str
    goal: str
    says: tuple[Say, ...]

    @property
    def length(self) -> int:
        return len(self.says)

    @property
    def texts(self) -> list[str]:
        return [say.text for say in self.says]

    def of(self, kind: str) -> tuple[int, ...]:
        """Номера ходов этого рода, считая с единицы."""
        return tuple(
            number for number, say in enumerate(self.says, start=1) if say.kind == kind
        )

    def as_dict(self) -> dict[str, object]:
        return {
            "key": self.key,
            "title": self.title,
            "goal": self.goal,
            "length": self.length,
            "says": [say.as_dict() for say in self.says],
        }


# --- сценарий A --------------------------------------------------------------
#
# Разговор про выбор модели памяти для своего чата. Ограничение ставится на
# третьем ходе и дальше обязано доживать до четырнадцатого; термин «уровень
# памяти» приравнивается к tier из day11 на пятом. Отвлечение на девятом уводит
# в day18, где про память нет вообще ничего.

MEMORY = Dialogue(
    key="memory",
    title="Выбор модели памяти для своего чата",
    goal="выбрать, как хранить контекст и память в своём чат-боте",
    says=(
        Say(
            "Мне нужно выбрать, как хранить контекст в своём чат-боте. "
            "Какие стратегии управления контекстом разобраны в day10?",
            GOAL,
            expect_paths=("day10/",),
            about="цель ставится первой репликой и дальше не повторяется",
        ),
        Say(
            "А какая из них самая дешёвая по токенам?",
            REFERENTIAL,
            expect_paths=("day10/",),
            about="«из них» указывает на список предыдущего хода",
        ),
        Say(
            "Важное ограничение: у меня только SQLite, никаких внешних сервисов "
            "и векторных баз. Где в day10 хранятся facts?",
            CONSTRAINT,
            expect_paths=("day10/",),
            must_say=("sqlite",),
            about="ограничение, которое должно дожить до конца разговора",
        ),
        Say(
            "А ключ и значение в ней как называются?",
            REFERENTIAL,
            expect_paths=("day10/",),
            about="«в ней» — таблица из предыдущего хода",
        ),
        Say(
            "Договоримся: под «уровнем памяти» я имею в виду то, что в day11 "
            "называется tier. Сколько уровней там всего?",
            TERM,
            expect_paths=("day11/",),
            must_say=("уровн",),
            about="термин: дальше ассистент обязан говорить «уровень», а не «tier»",
        ),
        Say(
            "Какие разделы у рабочей памяти в day11?",
            FOLLOWUP,
            expect_paths=("day11/",),
        ),
        Say(
            "А долговременная чем от неё отличается?",
            REFERENTIAL,
            expect_paths=("day11/",),
            must_not_say=("tier",),
            about="ссылка плюс проверка термина: `tier` в ответе — значит термин не принят",
        ),
        Say(
            "Раз у меня только SQLite — где именно day11 держит рабочую память?",
            PROBE,
            expect_paths=("day11/",),
            must_say=("sqlite",),
            about="ограничение названо на третьем ходе, сработать обязано здесь",
        ),
        Say(
            "Кстати, совсем про другое: на каком порту слушает MCP-сервер day18?",
            DIGRESSION,
            expect_paths=("day18/",),
            about="отвлечение: цель от него теряться не должна",
        ),
        Say(
            "Ладно, вернёмся к памяти. Как в day9 сжимается история диалога?",
            REFERENTIAL,
            expect_paths=("day9/",),
            about="возврат к цели после отвлечения",
        ),
        Say(
            "Сколько последних сообщений он оставляет дословно?",
            REFERENTIAL,
            expect_paths=("day9/",),
            about="«он» — механизм сжатия предыдущего хода",
        ),
        Say(
            "Что мне лучше взять в свой чат: сжатие истории из day9 "
            "или уровни памяти из day11?",
            PROBE,
            expect_paths=("day9/", "day11/"),
            must_not_say=("tier",),
            about="выбор возможен только с опорой на цель и ограничение",
        ),
        Say(
            "Если возьму второе — какие таблицы придётся завести?",
            REFERENTIAL,
            expect_paths=("day11/",),
            must_say=("longterm", "working"),
            about="«второе» указывает на вариант из предыдущего хода",
        ),
        Say(
            "И последнее: как мой чат будет выбирать, в какой уровень писать находку?",
            PROBE,
            expect_paths=("day11/",),
            must_not_say=("tier",),
            about="«мой чат» и «уровень» разом: и цель, и термин",
        ),
    ),
)


