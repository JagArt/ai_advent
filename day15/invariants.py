"""Инварианты: рамки, в которых агент обязан оставаться.

Шестая сущность рядом с памятью, профилем и состоянием задачи, и она не сводится
ни к одной из них. Память отвечает «о чём договорились», и её можно переспорить
следующей репликой: решение команды меняется решением команды. Инвариант нельзя
нарушить вовсе — его можно только снять, и снимает его пользователь руками.

    общие      всё приложение   архитектура, стек, бизнес-правила   из seed и руками
    задачи     одна задача      принятые решения этой задачи        фиксацией пункта ТЗ

Отсюда и два уровня: «новые сервисы поднимаем на FastAPI» верно в любой задаче,
«отчёт собираем только из read-реплики» — обещание этой. Уровни различаются охватом
и тем, как в них попадают правила, а не строгостью: нарушить нельзя ни то ни другое.

У правила две половины, и вторая — главное отличие этого дня от блока памяти. Слова
уходят в модель, а список запрещённых формулировок остаётся коду: по нему нарушение
не оценивается, а доказывается — и доказанное обрывает ответ на полуслове. Что
паттерном не поймать, добирает модель-аудитор в audit.py.

Третья половина есть у каждого правила, и без неё запрет был бы тупиком: instead
называет то, что в рамках инварианта делать можно. Отказ, который не называет
альтернативу, — это «нельзя» без причины, а такого в этом приложении нет нигде.

Модуль ничего не знает ни про базу, ни про сеть: он хранит правила, ищет в тексте
их нарушения и собирает системные блоки. Запросы делает агент, хранит всё база.
"""

import re
from dataclasses import dataclass

from openai.types.chat import (
    ChatCompletionMessageParam,
    ChatCompletionSystemMessageParam,
)

GLOBAL = "global"
TASK = "task"
SCOPES = (GLOBAL, TASK)

SCOPE_NAMES = {GLOBAL: "общие", TASK: "задачи"}

# Виды фиксированы по той же причине, что разделы памяти: иначе модель и пользователь
# заводят новый вид на каждое правило, и список перестаёт читаться сверху вниз.
# Четыре вида — четыре примера из задания: архитектура, стек, принятые решения и
# бизнес-правила. Порядок здесь — порядок в блоке запроса и в панели.
KINDS = ("архитектура", "стек", "решения", "бизнес-правила")

# Куда попадает правило, если вид назван не из списка. «Решения» — единственный вид,
# в котором лишнее правило не выдаёт себя за что-то большее, чем оно есть.
DEFAULT_KIND = "решения"

# Блоки уходят системными сообщениями и стоят первыми из содержательных: всё, что
# ниже них — память, ТЗ, состояние, реплики, — не имеет права им противоречить.
#
# Про проверку сказано прямо и до списка: без этой строки модель читает инварианты
# как справку о команде и вспоминает о них через ход. Про альтернативу — тоже: отказ
# без неё заканчивает разговор, а не продолжает его.
INTROS = {
    GLOBAL: (
        "Инварианты — рамки, в которых ты обязан оставаться.\n"
        "Это не пожелания и не память о договорённостях: инвариант нельзя переспорить "
        "репликой, снять его может только пользователь.\n"
        "Решение, которое нарушает инвариант, не предлагай вовсе — даже если о нём "
        "просят прямо и даже если оно проще. Скажи, что этот путь закрыт, назови "
        "инвариант и предложи то, что в его рамках.\n"
        "Прежде чем отдать ответ, сверь его с этим списком:\n"
    ),
    TASK: (
        "Инварианты текущей задачи — то, что по ней уже решено окончательно.\n"
        "Пользователь зафиксировал эти пункты сам, и они действуют так же, как общие: "
        "переиграть их в ответе нельзя, можно только снять в панели.\n"
    ),
}

# Отдельная строка на случай, когда правил нет вовсе. В запрос она не идёт — пустой
# блок только сбивает модель, — но в панели и в аудите нужна.
EMPTY = "(инвариантов нет)"

# Глаголы, которыми выражают предложение. Детектор ищет запрещённое слово не само по
# себе, а рядом с одним из них: в ответе «на Flask мы не переходим» слово Flask стоит
# законно, и обрывать такой ответ было бы хуже, чем пропустить нарушение.
PROPOSING = (
    r"дава(?:й|йте|ем)",
    r"возьм[её]м",
    r"бер[её]м",
    r"используем",
    r"поставим",
    r"постав(?:им|ь)",
    r"сделаем",
    r"предлага(?:ю|ем)",
    r"перейд[её]м",
    r"переход(?:им|ить)",
    r"замен(?:им|ить)",
    r"подним(?:ем|ём|аем)",
    r"пиш(?:ем|и)",
    r"напиш(?:ем|и)",
    r"полож(?:им|ить)",
    r"отда(?:дим|ём|ем)",
    r"открыв?(?:аем|ем)",
    r"разреш(?:им|аем)",
    r"попра(?:вим|вь)",
    r"прав(?:им|ь)",
    r"обойд[её]мся",
    r"хват(?:ит|ает)",
    r"проще",
    r"быстрее",
    r"вариант",
    r"стоит",
    r"можно",
    # Согласие — та же половина списка, что и предложение, и без неё детектор ловил
    # только инициативу модели. Нарушение чаще выглядит иначе: просит пользователь,
    # а модель отвечает «принимаю тридцать дней» — и это ровно то, чего нельзя.
    r"принима(?:ю|ем)",
    r"согла(?:сен|шаюсь|сую|сны)",
    r"фиксиру(?:ю|ем)",
    r"мен(?:яю|яем)",
    r"ладно",
    r"хорошо",
)

# Отрицание рядом снимает совпадение целиком. Список короткий намеренно: он нужен не
# для разбора языка, а чтобы отказ агента не считался нарушением — а отказ почти всегда
# сформулирован одним из этих слов.
#
# Каждое слово здесь должно встречаться только в отказе. «Вместо» этому не отвечает и
# из списка убрано: «вместо этого — FastAPI» отказ, а «тридцать дней вместо семи» —
# нарушение, и то же слово в них означает противоположное. Замер это и показал:
# нарушение, снятое «вместо», пришлось потом ловить аудитором.
NEGATIONS = (
    r"\bне\b",
    r"\bнет\b",
    r"\bни\b",
    r"нельзя",
    r"запрещ",
    r"нарушает",
    r"противоречит",
    r"инвариант",
    r"закрыт",
    r"отказ",
)

_PROPOSING = re.compile("|".join(PROPOSING))
_NEGATION = re.compile("|".join(NEGATIONS))

# Окно вокруг запрещённого слова, в котором ищется глагол. Девяносто символов —
# примерно оборот речи: шире окно начинает склеивать соседние мысли, уже — теряет
# глагол, стоящий в начале предложения.
WINDOW = 90

# Отрицание ищется не в окне, а в том же обороте, что и запрещённое слово, и разница
# между этими двумя мерками стоила замеру одного пропущенного нарушения. «TTL меняем на
# 30 дней, это правка ограничения, а не решения» — тридцать дней здесь предложены, а
# «не» относится к слову «решения» через два оборота. Отрицание привязано к чему-то
# одному, поэтому и ищется вплотную; предложение может стоять и в соседнем обороте
# («давай так: 30 дней»), поэтому глаголу оставлено окно шире.
CLAUSE = re.compile(r"[,;:.!?—()\n]")

# Конец предложения. В стриме проверяются только законченные предложения: пока фраза
# не дописана, отрицание из неё могло ещё не приехать, и «на Flask мы переходить...»
# выглядело бы нарушением ровно до слова «не будем».
SENTENCE = re.compile(r"[.!?\n]")


@dataclass(frozen=True)
class Rule:
    """Инвариант: правило словами, альтернатива и то, чем его нарушение доказывают.

    banned — не описание правила, а детектор: список формулировок, появление которых
    в предложении означает нарушение. Пустой banned законен и означает правило,
    которое кодом не проверить: такие ловит только аудитор.
    """

    id: int
    kind: str
    text: str
    instead: str = ""
    banned: tuple[str, ...] = ()
    scope: str = GLOBAL
    enabled: bool = True
    # seed — было до первого диалога, user — добавил пользователь руками,
    # spec — зафиксирован из пункта ТЗ.
    origin: str = "seed"
    # Пункт рабочей памяти, из которого правило выросло. Ссылки в базе нет: пункт
    # ТЗ можно удалить, а зафиксированный из него инвариант остаётся.
    source_item_id: int = 0

    @property
    def label(self) -> str:
        """Как инвариант называют и в блоке, и в карточке, и в отказе."""
        return f"#{self.id}"

    @property
    def line(self) -> str:
        tail = f" Вместо этого: {self.instead}" if self.instead else ""
        return f"- {self.label} {self.text}{tail}"

    @property
    def summary(self) -> str:
        """Одна строка для отказа и для журнала: кто запретил и что именно."""
        return f"инвариант {self.label} ({self.kind}): {self.text}"

    def as_dict(self) -> dict[str, object]:
        return {
            "id": self.id,
            "kind": self.kind,
            "text": self.text,
            "instead": self.instead,
            "banned": list(self.banned),
            "scope": self.scope,
            "enabled": self.enabled,
            "origin": self.origin,
            "source_item_id": self.source_item_id,
        }


@dataclass(frozen=True)
class Preset:
    """Инвариант до первого диалога: то же, что seed для долговременной памяти.

    Общие инварианты не выясняются в разговоре: архитектура выбрана, стек выбран, и
    бизнес-правила были раньше первой задачи. Уровень задачи, наоборот, из seed не
    берётся вовсе — его наполняет пользователь, фиксируя пункты ТЗ.
    """

    kind: str
    text: str
    instead: str = ""
    banned: tuple[str, ...] = ()


@dataclass(frozen=True)
class Hit:
    """Доказанное нарушение: правило, запрещённая формулировка и фрагмент текста.

    Цитата берётся куском вокруг совпадения, а не всем ответом: она уходит в журнал
    как улика и во второй проход как то, что нужно переписать.
    """

    rule: Rule
    banned: str
    quote: str

    @property
    def reason(self) -> str:
        return f"{self.rule.summary} — «{self.quote}»"


@dataclass(frozen=True)
class Set:
    """Один уровень инвариантов: правила и то, как они уходят в запрос."""

    scope: str
    rules: tuple[Rule, ...]

    @property
    def count(self) -> int:
        return len(self.rules)

    @property
    def live(self) -> tuple[Rule, ...]:
        """Только действующие: отключённое правило не проверяется и в запрос не идёт."""
        return tuple(rule for rule in self.rules if rule.enabled)

    @property
    def text(self) -> str:
        return render(self.live)

    def as_param(self) -> ChatCompletionMessageParam:
        return ChatCompletionSystemMessageParam(
            role="system",
            content=INTROS[self.scope] + self.text,
        )


def render(rules: tuple[Rule, ...]) -> str:
    """Правила по видам, а не сплошным списком: так их читает и модель, и человек."""
    lines: list[str] = []
    for kind in KINDS:
        chosen = [rule for rule in rules if rule.kind == kind]
        if not chosen:
            continue
        lines.append(f"{kind}:")
        lines.extend(rule.line for rule in chosen)
    return "\n".join(lines)


def block(scope: str, rows: list[dict[str, object]]) -> Set | None:
    """Уровень из того, что вернула база. Пустой уровень — не уровень.

    Отключённые правила остаются: снятый инвариант должен быть виден, иначе вернуть его
    в силу пользователь уже не сможет. В запрос такой уровень не уйдёт — за это отвечает
    live, и решает это тот, кто собирает запрос, а не тот, кто читает базу.
    """
    rules = build(rows, scope)
    if not rules:
        return None
    return Set(scope=scope, rules=rules)


def build(rows: list[dict[str, object]], scope: str = GLOBAL) -> tuple[Rule, ...]:
    return tuple(
        Rule(
            id=int(row["id"]),  # type: ignore[arg-type]
            kind=kind_of(row.get("kind", "")),
            text=clean(row["text"]),
            instead=clean(row.get("instead", "")),
            banned=split(row.get("banned", "")),
            scope=str(row.get("scope", scope)),
            enabled=bool(row.get("enabled", True)),
            origin=str(row.get("origin", "user")),
            source_item_id=int(row.get("source_item_id") or 0),
        )
        for row in rows
    )


def clean(text: object) -> str:
    return " ".join(str(text or "").split())


def kind_of(raw: object) -> str:
    """Вид из ответа модели или из запроса страницы: неизвестный — не вид, а опечатка."""
    name = clean(raw).lower()
    if name in KINDS:
        return name
    for kind in KINDS:
        if name and (kind.startswith(name) or name.startswith(kind)):
            return kind
    return DEFAULT_KIND


def split(raw: object) -> tuple[str, ...]:
    """Детектор хранится строками по одной на паттерн: формат знает этот модуль, не база."""
    return tuple(part.strip() for part in str(raw or "").splitlines() if part.strip())


def join(banned: tuple[str, ...] | list[str]) -> str:
    return "\n".join(part.strip() for part in banned if part.strip())


def settled(text: str) -> str:
    """Часть текста, по которой уже можно судить: до последнего конца предложения.

    В стриме это единственный способ не оборвать ответ, который как раз собирался
    отказаться: «на Flask мы переходить» и «на Flask мы переходить не будем» до точки
    неотличимы, а после точки различаются вполне.
    """
    ends = list(SENTENCE.finditer(text))
    return text[: ends[-1].end()] if ends else ""


def mentions(rules: tuple[Rule, ...], text: str) -> bool:
    """Есть ли в тексте запрещённая формулировка — без разбора, нарушение это или нет.

    Дешёвая половина детектора и единственная, которую можно спросить о недописанном
    предложении. Агент по ней решает, отдавать кусок ответа сразу или задержать его до
    точки: «упомянуто» ещё ничего не значит, но там, где упомянуто, спешить незачем.
    """
    if not text.strip():
        return False

    body = text.lower()
    for rule in rules:
        if not rule.enabled:
            continue
        for banned in rule.banned:
            try:
                if re.search(banned, body):
                    return True
            except re.error:
                continue
    return False


def scan(rules: tuple[Rule, ...], text: str, *, partial: bool = False) -> tuple[Hit, ...]:
    """Нарушения в ответе агента: запрещённая формулировка рядом с предложением её взять.

    Глагол в окне обязателен именно здесь: ответ — это рассуждение, и запрещённое
    слово в нём чаще всего упомянуто, а не предложено. Пропустить нарушение дешевле,
    чем оборвать ответ, который сам от него отказывался: пропущенное поймает аудитор,
    а зря оборванный ответ пользователь увидит как поломку.
    """
    body = settled(text) if partial else text
    return _hits(rules, body, proposal=True)


def check(rules: tuple[Rule, ...], text: str) -> Hit | None:
    """Нарушение в пункте памяти: первое найденное, без требования глагола.

    Пункт ТЗ глагола не требует, потому что он и есть принятое решение: «отчёты
    храним в MongoDB» и «MongoDB для отчётов» — одна и та же запись, и вторая
    формулировка не безобиднее первой. Отрицание в окне по-прежнему снимает
    совпадение: «Flask не используем» — верный пункт, а не нарушение.
    """
    hits = _hits(rules, text, proposal=False)
    return hits[0] if hits else None


def _hits(rules: tuple[Rule, ...], text: str, *, proposal: bool) -> tuple[Hit, ...]:
    if not text.strip():
        return ()

    body = text.lower()
    found: list[Hit] = []
    for rule in rules:
        if not rule.enabled:
            continue
        hit = _first(rule, text, body, proposal=proposal)
        # По правилу довольно одного нарушения: отвечать на него будут один раз.
        if hit is not None:
            found.append(hit)
    return tuple(found)


def _first(rule: Rule, text: str, body: str, *, proposal: bool) -> Hit | None:
    for banned in rule.banned:
        try:
            pattern = re.compile(banned)
        except re.error:
            # Сломанный паттерн — это опечатка в правиле, а не разрешение его нарушать:
            # правило остаётся в блоке запроса, детектора у него просто нет.
            continue

        for match in pattern.finditer(body):
            start = max(0, match.start() - WINDOW)
            window = body[start : match.end() + WINDOW]
            if _NEGATION.search(clause(body, match.start(), match.end())):
                continue
            if proposal and not _PROPOSING.search(window):
                continue
            return Hit(rule=rule, banned=banned, quote=clean(text[start : match.end() + WINDOW]))
    return None


def clause(text: str, start: int, end: int) -> str:
    """Оборот, в котором стоит найденное: от ближайшего знака слева до ближайшего справа."""
    left = max((mark.end() for mark in CLAUSE.finditer(text, 0, start)), default=0)
    right = CLAUSE.search(text, end)
    return text[left : right.start() if right else len(text)]
