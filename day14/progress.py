"""Предложение двинуть автомат: что модель считает пройденным по итогам хода.

Отдельный запрос и отдельный модуль, а не поле в разборе находок. Причина не в
экономии строк: remember.py отвечает на вопрос «куда положить сказанное», а здесь
вопрос другой — «сделано ли то, чего ждали». Смешанные в одном JSON, они путаются:
модель начинает двигать этап потому, что нашла что записать, и записывать потому,
что решила двинуть этап. Запросы уходят одновременно, так что ход от этого не
медленнее.

Решение модуль не принимает и допустимость не проверяет — он только читает ответ
модели. Проверяет task.find по графу и условиям, применяет агент, а решает
пользователь карточкой. Названного перехода нет в списке или условие не выполнено —
предложение отбрасывается целиком, ровно как выдуманное значение шкалы в day12:
состояние, которое двинулось не по правилам, хуже, чем состояние, которое стоит.
"""

import json
from dataclasses import dataclass

from openai.types.chat import (
    ChatCompletionMessageParam,
    ChatCompletionSystemMessageParam,
    ChatCompletionUserMessageParam,
)

from memory import Store
from task import STAGE, STEP, Move, Task

# Разбор хода — не разговор: нужна оценка сделанного, а не рассуждение о нём.
TEMPERATURE = 0.0
MAX_TOKENS = 250

EMPTY = "(пусто)"

PROMPT = """\
Ты следишь за состоянием задачи. Оно устроено как конечный автомат: этап, шаг внутри
этапа и ожидаемое от пользователя действие. Твоё дело — решить, сделано ли по итогам
последнего обмена репликами то, чего ждали на текущем шаге.

На входе — состояние, список допустимых отсюда переходов, техническое задание задачи
и последний обмен репликами.

Правила:
- Выбирай ровно один переход из списка или не выбирай ни одного.
- Своих переходов не придумывай: чего в списке нет, того не бывает.
- Переход с пометкой «закрыт» не предлагай: условие ещё не выполнено, и предложение
  будет отброшено.
- Двигай состояние по тому, что пользователь подтвердил и что попало в ТЗ, а не по
  тому, что вы обсудили. «Давай подумаем» и «наверное, так» — не выполненное действие.
- Ожидаемое действие выполнено наполовину — перехода нет. Шаг закрывают целиком.
- Откат предлагай только тогда, когда пользователь отменил или переиграл уже
  принятое: изменился объём задачи, нашли пробел в готовом ТЗ.
- Задачу готовой сам не объявляй: этап done открывается тем же переходом, что и все
  остальные, и только когда его условие выполнено.

Поле why — одна короткая строка, почему шаг считается пройденным: её увидит
пользователь рядом с кнопкой.

Верни строго JSON без markdown и пояснений:
{"move": {"stage": "execution", "why": "..."}}
или
{"move": {"step": "требования", "why": "..."}}
Двигаться некуда — верни {"move": null}.
"""


@dataclass(frozen=True)
class Suggestion:
    """Что назвала модель. Ещё не переход: имя цели и причина, больше ничего."""

    stage: str
    step: str
    why: str = ""


def clean(text: object) -> str:
    return " ".join(str(text).split())


def state(task: Task, moves: tuple[Move, ...], tally: dict[str, int]) -> str:
    """Состояние и переходы словами: то же, что видит пользователь в панели.

    Закрытые переходы уходят в модель вместе с причиной, а не скрываются от неё.
    Спрятать их значило бы получать предложения наугад: модель всё равно назовёт
    следующий этап, но уже не понимая, чего для него не хватает.
    """
    lines = [*task.lines(tally), "", "Допустимые переходы:"]
    if not moves:
        lines.append("- нет ни одного")
    for move in moves:
        target = f"stage: {move.stage}" if move.kind == STAGE else f"step: {move.step}"
        note = "" if move.allowed else f" — закрыт, {move.blocked}"
        lines.append(f"- {move.name} ({target}){note}")
    return "\n".join(lines)


def request(
    task: Task,
    moves: tuple[Move, ...],
    tally: dict[str, int],
    working: Store | None,
    prompt: str,
    answer: str,
) -> list[ChatCompletionMessageParam]:
    """Ход уходит на оценку расшифровкой, а не диалогом — как и разбор находок.

    ТЗ едет вместе с состоянием: условия шагов считаются по нему, и без него модель
    судит о пройденном по одной последней реплике.
    """
    return [
        ChatCompletionSystemMessageParam(role="system", content=PROMPT),
        ChatCompletionUserMessageParam(
            role="user",
            content=(
                f"Состояние задачи:\n{state(task, moves, tally)}\n\n"
                f"Рабочая память — ТЗ задачи:\n{working.text if working else EMPTY}\n\n"
                f"Последний обмен:\nПользователь: {prompt}\nАссистент: {answer}"
            ),
        ),
    ]


def clean_json(text: str) -> str:
    body = text.strip()
    if body.startswith("```"):
        body = body.removeprefix("```json").removeprefix("```").removesuffix("```")
    return body.strip()


def parse(text: str) -> Suggestion | None:
    """Разбор ответа модели: одно предложение или ничего.

    Пустой ответ и «двигаться некуда» — одно и то же и ошибкой не считаются: ход,
    на котором автомат стоит, — обычный ход, а не сбой разбора.
    """
    body = clean_json(text)
    try:
        parsed = json.loads(body)
    except ValueError as error:
        raise ValueError(f"ответ не разобран как JSON: {clean(text)[:80]}") from error

    if not isinstance(parsed, dict):
        raise ValueError("ожидался объект с полем move")

    # Модель иногда отдаёт переход без обёртки move: форма не та, содержимое то самое.
    move = parsed.get("move", parsed)
    if not isinstance(move, dict):
        return None

    stage = clean(move.get(STAGE, "")).lower()
    step = clean(move.get(STEP, "")).lower()
    if not stage and not step:
        return None

    # Названы оба поля — это не переход, а два разных: этап и шаг двигаются по
    # отдельности, и «куда-нибудь из двух» не решение. Ведущим считается этап:
    # переход между этапами всё равно ставит шаг сам, первым в новом этапе.
    return Suggestion(stage=stage, step="" if stage else step, why=clean(move.get("why", "")))
