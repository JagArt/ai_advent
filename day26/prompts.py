"""Три запроса по нарастающей: факт, код, многошаговая задача.

Сложность растёт не длиной вопроса, а тем, сколько модели нужно сделать до
ответа: вспомнить одно слово, написать и проверить функцию, удержать в голове
цепочку условий. У последнего запроса есть единственный верный ответ — 8 — по
нему видно, справилась ли 4B-модель, а не только ответила ли.
"""

from dataclasses import asdict, dataclass


@dataclass(frozen=True)
class Prompt:
    id: str
    level: str
    text: str
    expected: str


PROMPTS: list[Prompt] = [
    Prompt(
        id="simple",
        level="простой",
        text="Какая столица Франции? Ответь одним словом.",
        expected="Париж",
    ),
    Prompt(
        id="medium",
        level="средний",
        text=(
            "Напиши на Python функцию is_palindrome(s), которая проверяет, является ли строка "
            "палиндромом, игнорируя регистр, пробелы и знаки препинания. "
            "Покажи два примера вызова с результатом."
        ),
        expected="«А роза упала на лапу Азора» → True",
    ),
    Prompt(
        id="hard",
        level="сложный",
        text=(
            "В корзине 5 яблок. Аня взяла треть оставшихся после того, как Борис забрал 2. "
            "Потом Вика положила в корзину вдвое больше яблок, чем взяла Аня, "
            "а Глеб съел одно из корзины. Затем в корзину добавили ещё 5. "
            "Сколько яблок в корзине? Распиши шаги и дай итоговое число."
        ),
        expected="5 − 2 = 3; Аня 1 → 2; Вика +2 → 4; Глеб −1 → 3; +5 → 8",
    ),
]


def as_json() -> list[dict]:
    return [asdict(prompt) for prompt in PROMPTS]
